-- 1. Nombres largos y fechas opcionales (muchas becas no publican alguna de las dos)
ALTER TABLE ayuda_financiera
  ALTER COLUMN nombre       TYPE varchar(300),
  ALTER COLUMN fecha_inicio DROP NOT NULL,
  ALTER COLUMN fecha_limite DROP NOT NULL;

ALTER TABLE entidad_financiera
  ALTER COLUMN nombre TYPE varchar(200);

-- 2. Columnas nuevas (las filas que ya existen quedan con fuente/id_externo NULL y el scraper no las toca)
ALTER TABLE ayuda_financiera
  ADD COLUMN fuente               text,
  ADD COLUMN id_externo           text,
  ADD COLUMN niveles              text[]  NOT NULL DEFAULT '{}',
  ADD COLUMN tipos_apoyo          text[]  NOT NULL DEFAULT '{}',
  ADD COLUMN departamento         text,
  ADD COLUMN ciudad               text,
  ADD COLUMN region               text,
  ADD COLUMN ubicacion            text,
  ADD COLUMN ciclo                text,
  ADD COLUMN cobertura            text,
  ADD COLUMN requisitos_lista     jsonb   NOT NULL DEFAULT '[]',
  ADD COLUMN enlace_terminos      text,
  ADD COLUMN enlace_postulacion   text,
  ADD COLUMN nota                 text,
  ADD COLUMN recursos             jsonb   NOT NULL DEFAULT '[]',
  ADD COLUMN acepta_postulaciones boolean,
  ADD COLUMN hash_contenido       text,
  ADD COLUMN activa               boolean NOT NULL DEFAULT true,
  ADD COLUMN corridas_ausente     integer NOT NULL DEFAULT 0,
  ADD COLUMN requiere_revision    boolean NOT NULL DEFAULT false,
  ADD COLUMN fecha_subida         timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN fecha_revision       timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN fecha_actualizacion  timestamptz NOT NULL DEFAULT now();

-- 3. Restricciones
ALTER TABLE ayuda_financiera
  ADD CONSTRAINT ck_ayuda_niveles
    CHECK (niveles <@ ARRAY['pregrado','posgrado']::text[]),
  ADD CONSTRAINT ck_ayuda_tipos_apoyo
    CHECK (tipos_apoyo <@ ARRAY['beca','credito_condonable','descuento','sostenimiento','programa']::text[]),
  ADD CONSTRAINT ck_ayuda_fuente_externo
    CHECK ((fuente IS NULL) = (id_externo IS NULL)),
  ADD CONSTRAINT uq_ayuda_id_externo UNIQUE (id_externo);

-- 4. Índices para los filtros
CREATE INDEX idx_ayuda_niveles      ON ayuda_financiera USING GIN (niveles);
CREATE INDEX idx_ayuda_tipos_apoyo  ON ayuda_financiera USING GIN (tipos_apoyo);
CREATE INDEX idx_ayuda_fecha_limite ON ayuda_financiera (fecha_limite);

-- El scraper busca o crea la entidad por nombre
CREATE UNIQUE INDEX ux_entidad_financiera_nombre ON entidad_financiera (lower(nombre));

-- 5. Instituciones aliadas de una ayuda (p. ej. las del Banco de Programas de Becas SER)
CREATE TABLE ayuda_financiera_ies (
  id_ayuda        bigint NOT NULL REFERENCES ayuda_financiera(id_ayuda) ON DELETE CASCADE,
  clave           text   NOT NULL,
  nombre_fuente   text   NOT NULL,
  departamento    text   NOT NULL,
  id_institucion  bigint REFERENCES institucion(id_institucion),
  activa          boolean NOT NULL DEFAULT true,
  fecha_revision  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id_ayuda, clave)
);
CREATE INDEX idx_ayuda_ies_institucion ON ayuda_financiera_ies (id_institucion);

-- 6. Historial de corridas de importación
CREATE TABLE ayuda_financiera_corrida (
  id_corrida   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fuente       text NOT NULL,
  inicio       timestamptz NOT NULL DEFAULT now(),
  fin          timestamptz,
  estado       text NOT NULL,
  encontradas  int NOT NULL DEFAULT 0,
  nuevas       int NOT NULL DEFAULT 0,
  actualizadas int NOT NULL DEFAULT 0,
  desactivadas int NOT NULL DEFAULT 0,
  error        text
);
